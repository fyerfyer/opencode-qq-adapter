import { mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { EnvEditor } from "../../src/admin/env-editor.js";
import { AdminError } from "../../src/admin/errors.js";

const roots: string[] = [];

afterEach(async () => {
  for (const root of roots.reverse()) await rm(root, { recursive: true, force: true });
  roots.length = 0;
});

async function tempEnv(): Promise<{ dir: string; path: string; editor: EnvEditor }> {
  const dir = await mkdtemp(join(tmpdir(), "qq-env-editor-"));
  roots.push(dir);
  const path = join(dir, ".env");
  return { dir, path, editor: new EnvEditor(path) };
}

describe("EnvEditor", () => {
  it("reads a missing file as empty", async () => {
    const { editor } = await tempEnv();
    await expect(editor.read()).resolves.toMatchObject({
      exists: false,
      hash: null,
      values: {},
    });
  });

  it("updates existing keys, preserves comments and appends new keys", async () => {
    const { path, editor } = await tempEnv();
    await writeFile(
      path,
      [
        "# generated by setup",
        "NAPCAT_WS_URL=ws://old",
        "export KEEP=this-value",
        "# comment",
        "NAPCAT_ACCESS_TOKEN='old token'",
        "",
      ].join("\n"),
      { encoding: "utf8", mode: 0o600 },
    );

    const snapshot = await editor.update({
      NAPCAT_WS_URL: "ws://127.0.0.1:3001",
      NAPCAT_ACCESS_TOKEN: "new-token",
      JEV_API_KEY: "jev-key",
    });

    expect(snapshot.exists).toBe(true);
    expect(snapshot.values).toMatchObject({
      NAPCAT_WS_URL: "ws://127.0.0.1:3001",
      KEEP: "this-value",
      NAPCAT_ACCESS_TOKEN: "new-token",
      JEV_API_KEY: "jev-key",
    });
    expect(snapshot.backup).toMatch(/\.env\.bak\./);
    expect(await readFile(path, "utf8")).toContain("# generated by setup");
    expect((await stat(path)).mode & 0o777).toBe(0o600);
  });

  it("rejects a stale expected hash", async () => {
    const { path, editor } = await tempEnv();
    await writeFile(path, "A=1\n", "utf8");
    await expect(editor.update({ A: "2" }, "stale")).rejects.toMatchObject({
      code: "env_conflict",
      status: 409,
    });
  });

  it("rejects unrepresentable values without revealing them", async () => {
    const { editor } = await tempEnv();
    await expect(editor.update({ TOKEN: "line1\nline2" })).rejects.toBeInstanceOf(AdminError);
    await expect(editor.update({ TOKEN: "a'b\"c" })).rejects.toMatchObject({
      code: "env_invalid_value",
    });
  });
});
